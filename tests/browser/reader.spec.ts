  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Selected word', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Chinese passage').getByRole('button', { name: /^下午,/ })).toBeFocused()
