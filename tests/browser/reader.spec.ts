  await page.getByRole('button', { name: 'Back to reading', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'An afternoon at the café' })).toBeVisible()
  await expect(word.getByRole('img', { name: 'Tone guide: 1 high and level, 1 high and level' })).toBeAttached()
  expect(await word.locator('span').filter({ hasText: /^jīn tiān$/ }).last().evaluate(el => getComputedStyle(el).fontFamily)).toContain('monospace')
  expect(await word.locator('span[lang=en]').evaluate(el => getComputedStyle(el).fontSize)).toBe('33.75px')
  expect(await word.evaluate(el => !!(el.compareDocumentPosition(el.closest('article')!.querySelector('p[lang=en]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await page.getByRole('button', { name: 'Open profile', exact: true }).click()
  await page.reload()
