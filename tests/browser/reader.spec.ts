  await expect(page.getByLabel('Sentence translation position', { exact: true })).toHaveValue('below')
  await expect(page.getByLabel('Interface text size', { exact: true })).toHaveValue('lg')
  await expect(page.getByLabel('Reading text size', { exact: true })).toHaveValue('48')
  await expect(page.getByLabel('Pinyin font', { exact: true })).toHaveValue('mono')
  await expect(page.getByLabel('Chinese characters (字) font', { exact: true })).toHaveValue('serif')
  await expect(page.getByLabel('Translation size', { exact: true })).toHaveValue('30')
